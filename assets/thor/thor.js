/* ============================================================================
   thor.js — motion for a still engraving.

   Three effects, none of which generate new artwork: everything you see is the
   original 1870s wood engraving with its own pixels pushed around, plus light
   added on top. That constraint is the point. A video model would re-render
   the hatching into soup; moving the existing pixels keeps every line the
   engraver cut.

     · The smoke is a domain-warped flow field over the drawn clouds, with the
       field varying across the frame — fast and upward at the vent above the
       crag, slow and lateral at the top. A uniform warp is what produces the
       "underwater jelly" look that reads as fake instantly.

     · The beard and the drape are displaced by a wave that travels from the
       anchored end outward, with amplitude ramped along the length so there is
       exactly zero movement where the beard meets his jaw and where the cloth
       meets his belt. They share one wind field, so they gust together; the
       cloth is given a longer period and a lag, because cloth is heavier than
       hair.

     · The hammer charges rather than flashes: a long rise, a short peak, a
       quick decay, a beat of rest. Arcs are generated by midpoint displacement
       and thrown away every cycle. The light also spills onto his fist, his
       forearm and the near rock — the detail that stops it reading as a sticker.

   All noise is lattice-periodic, so a loop of LOOP seconds is seamless and the
   whole thing can be captured as a GIF with no crossfade and no visible seam.
   ========================================================================== */

const VERT = `#version 300 es
in vec2 a_pos;
out vec2 v_uv;
void main() {
  v_uv = a_pos * 0.5 + 0.5;
  gl_Position = vec4(a_pos, 0.0, 1.0);
}`;

const FRAG = `#version 300 es
precision highp float;

in vec2 v_uv;
out vec4 outColor;

uniform sampler2D u_src;    // the engraving
uniform sampler2D u_mask;   // R smoke · G beard+hair · B drape · A figure
uniform sampler2D u_bolt;   // arcs, drawn on a 2D canvas each frame

uniform vec2  u_crop0;      // crop rectangle in source UV space
uniform vec2  u_crop1;
uniform float u_t;          // seconds, wrapped to the loop
uniform float u_loop;       // loop length in seconds
uniform float u_charge;     // 0..1 hammer envelope
uniform vec2  u_hammer;     // hammer head, in crop UV
uniform vec2  u_fist;       // his hand on the haft, in crop UV
uniform vec2  u_vent;       // where the plume comes from, in crop UV
uniform float u_amp;        // global motion scale, for reduced-motion
uniform float u_debug;      // 1 = show the masks as the shader actually reads them

/* ── periodic value noise ──────────────────────────────────────────────────
   The lattice wraps at PER, so scrolling the field by exactly PER over one
   loop returns it to where it started. That is what makes a seamless GIF
   possible without crossfading two copies of the animation together. */
const float PER = 8.0;

float hash(vec2 p) {
  p = mod(p, PER);
  return fract(sin(dot(p, vec2(127.1, 311.7))) * 43758.5453);
}

float vnoise(vec2 p) {
  vec2 i = floor(p), f = fract(p);
  vec2 u = f * f * (3.0 - 2.0 * f);
  return mix(mix(hash(i), hash(i + vec2(1, 0)), u.x),
             mix(hash(i + vec2(0, 1)), hash(i + vec2(1, 1)), u.x), u.y);
}

float fbm(vec2 p) {
  return 0.60 * vnoise(p) + 0.28 * vnoise(p * 2.0) + 0.12 * vnoise(p * 4.0);
}

/* One wind field, shared. Beard and cloth must gust together or they read as
   two independent stickers. Periodic in u_loop by construction. */
float wind(float t) {
  float a = sin(6.2831853 * t / u_loop);
  float b = sin(6.2831853 * 2.0 * t / u_loop + 1.7);
  float c = sin(6.2831853 * 3.0 * t / u_loop + 4.1);
  return 0.55 + 0.28 * a + 0.13 * b + 0.07 * c;   // 0.07 .. 1.03, never still
}

void main() {
  vec2 uv = v_uv;
  vec2 suv = mix(u_crop0, u_crop1, uv);            // into the source image
  vec4 m = texture(u_mask, suv);

  float gust = wind(u_t);
  float scroll = u_t / u_loop * PER;               // exactly one lattice period
  vec2 push = vec2(0.0);

  /* ── smoke ─────────────────────────────────────────────────────────────
     Domain warp: a slow large octave displaced by a faster small one. Both
     sample a field that scrolls upward, so the plume genuinely rises instead
     of wobbling in place. */
  if (m.r > 0.004) {
    vec2 p = uv * vec2(2.6, 3.0);
    vec2 q = vec2(fbm(p + vec2(0.0, -scroll * 0.30)),
                  fbm(p + vec2(5.2, 1.3) + vec2(0.0, -scroll * 0.30)));
    vec2 r = vec2(fbm(p * 2.3 + q * 1.1 + vec2(0.0, -scroll * 0.62)),
                  fbm(p * 2.3 + q * 1.1 + vec2(3.7, 9.1) + vec2(0.0, -scroll * 0.62)));

    vec2 curl = (q - 0.5) * 0.020 + (r - 0.5) * 0.011;

    /* The field has to vary across the frame or the whole sky slides as one
       sheet. Near the vent it is fast and vertical; away from it the rise
       falls off and the motion turns lateral, the way a plume actually
       spreads as it cools. */
    float d = distance(uv, u_vent);
    float near = exp(-d * d / (2.0 * 0.30 * 0.30));
    float rise = -0.016 * near * (0.75 + 0.45 * gust);
    curl.y += rise;
    curl.x *= 1.0 + 1.5 * (1.0 - near);            // spread, up high
    curl.y *= 0.55 + 0.85 * near;

    push += curl * m.r;
  }

  /* ── beard and drape ───────────────────────────────────────────────────
     The mask value doubles as a normalised distance from the anchor — zero at
     the jaw, one at the tip — so using it as the wave's phase makes the wave
     travel outward along the length instead of the whole thing oscillating in
     place. That, and the fact that it is zero at the root, is the difference
     between hair moving and a sticker vibrating. */
  if (m.g > 0.004) {
    float along = m.g;
    float ph = along * 7.0 - u_t * 3.6;
    float sway = sin(ph) * 0.55 + sin(ph * 1.9 + 1.1) * 0.28;
    float a = along * (0.34 + 0.66 * gust) * 0.0085;
    push += vec2(sway * a, sin(ph * 0.8 + 0.6) * a * 0.34);
  }

  if (m.b > 0.004) {
    /* Heavier: slower, and a beat behind the same gust. */
    float along = m.b;
    float ph = along * 5.2 - u_t * 2.35;
    float lag = wind(u_t - 0.22);
    float sway = sin(ph) * 0.6 + sin(ph * 1.6 + 2.3) * 0.24;
    float a = along * (0.30 + 0.70 * lag) * 0.0115;
    push += vec2(sway * a, cos(ph * 0.7) * a * 0.30);
  }

  vec2 sample_uv = suv + push * u_amp * (u_crop1 - u_crop0);
  vec3 col = texture(u_src, sample_uv).rgb;

  /* ── the hammer ────────────────────────────────────────────────────────
     Light that does not touch anything around it reads as pasted on, so the
     glow is applied to the plate itself: a core at the head, and a weaker
     spill reaching his fist and forearm. Screen-blended, because the engraving
     is ink on white and light means less ink. */
  float ch = u_charge;
  if (ch > 0.001) {
    float dh = distance(uv, u_hammer);
    float core = exp(-dh * dh / (2.0 * 0.030 * 0.030));
    float halo = exp(-dh * dh / (2.0 * 0.095 * 0.095));

    float df = distance(uv, u_fist);
    float spill = exp(-df * df / (2.0 * 0.070 * 0.070));

    /* Kept deliberately low. The engraving is already blown out to paper white
       just right of his head; a glow that competes with that reads as a bug in
       the image rather than as light in the scene. */
    float lift = ch * (core * 0.34 + halo * 0.12 + spill * 0.10);
    /* Bias the lift toward pixels that already have some tone. Blasting the
       deepest blacks to grey flattens the hatching and the engraving stops
       looking like an engraving. */
    float tone = 0.35 + 0.65 * col.r;
    col = 1.0 - (1.0 - col) * (1.0 - clamp(lift * tone, 0.0, 0.72));
  }

  /* ── arcs ──────────────────────────────────────────────────────────────
     Drawn in 2D and composited here, so the arc generator can be ordinary
     JavaScript and the whole frame still leaves as one canvas. */
  float bolt = texture(u_bolt, uv).r;
  col = 1.0 - (1.0 - col) * (1.0 - bolt);

  if (u_debug > 0.5) { outColor = vec4(m.r, m.g, m.b, 1.0); return; }
  outColor = vec4(col, 1.0);
}`;

/* ── lightning ─────────────────────────────────────────────────────────────
   Midpoint displacement: take a segment, kick its midpoint sideways by a
   random amount, recurse, halving the amount each time. It is the standard
   way to draw lightning and it looks right because it is self-similar the way
   a real discharge is.

   Seeded, so a given cycle index always produces the same bolt — which is what
   lets a two-cycle loop repeat exactly while still looking different each
   time within the loop. */
function mulberry32(a) {
  return function () {
    a |= 0; a = (a + 0x6D2B79F5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function bolt(rng, x0, y0, x1, y1, spread, depth) {
  let pts = [[x0, y0], [x1, y1]];
  for (let d = 0; d < depth; d++) {
    const next = [pts[0]];
    for (let i = 0; i < pts.length - 1; i++) {
      const [ax, ay] = pts[i], [bx, by] = pts[i + 1];
      const mx = (ax + bx) / 2, my = (ay + by) / 2;
      const dx = bx - ax, dy = by - ay;
      const len = Math.hypot(dx, dy) || 1;
      const off = (rng() - 0.5) * spread;
      next.push([mx - (dy / len) * off, my + (dx / len) * off]);
      next.push(pts[i + 1]);
    }
    pts = next;
    spread *= 0.55;
  }
  return pts;
}

/**
 * @param {HTMLCanvasElement} canvas
 * @param {object} opts
 * @param {HTMLImageElement} opts.src   the engraving
 * @param {HTMLImageElement} opts.mask  the mask atlas
 * @param {number[]} opts.crop          [x0,y0,x1,y1], in `ref` pixels
 * @param {number[]} [opts.ref]         the coordinate space crop/landmarks are
 *   quoted in, default the original plate's 1329x1600. Everything measured off
 *   the engraving is written in those numbers and stays readable, while the
 *   plate and the masks are free to ship at whatever resolution compresses
 *   best — they are different sizes from each other already.
 * @param {number} [opts.loop]          seconds; the animation is periodic in this
 * @param {number} [opts.cycles]        hammer charges per loop
 */
export function createThor(canvas, opts) {
  const { src, mask, crop, loop = 8.0, cycles = 2, ref = [1329, 1600] } = opts;
  const gl = canvas.getContext("webgl2", { antialias: false, preserveDrawingBuffer: true });
  if (!gl) throw new Error("WebGL2 unavailable");

  const compile = (type, s) => {
    const sh = gl.createShader(type);
    gl.shaderSource(sh, s);
    gl.compileShader(sh);
    if (!gl.getShaderParameter(sh, gl.COMPILE_STATUS)) {
      throw new Error(gl.getShaderInfoLog(sh) || "shader failed");
    }
    return sh;
  };
  const prog = gl.createProgram();
  gl.attachShader(prog, compile(gl.VERTEX_SHADER, VERT));
  gl.attachShader(prog, compile(gl.FRAGMENT_SHADER, FRAG));
  gl.linkProgram(prog);
  if (!gl.getProgramParameter(prog, gl.LINK_STATUS)) {
    throw new Error(gl.getProgramInfoLog(prog) || "link failed");
  }
  gl.useProgram(prog);

  const vao = gl.createVertexArray();
  gl.bindVertexArray(vao);
  const buf = gl.createBuffer();
  gl.bindBuffer(gl.ARRAY_BUFFER, buf);
  gl.bufferData(gl.ARRAY_BUFFER, new Float32Array([-1, -1, 3, -1, -1, 3]), gl.STATIC_DRAW);
  const loc = gl.getAttribLocation(prog, "a_pos");
  gl.enableVertexAttribArray(loc);
  gl.vertexAttribPointer(loc, 2, gl.FLOAT, false, 0, 0);

  function tex(unit, image, wrap) {
    const t = gl.createTexture();
    gl.activeTexture(gl.TEXTURE0 + unit);
    gl.bindTexture(gl.TEXTURE_2D, t);
    gl.texParameteri(gl.TEXTURE_2D, gl.TEXTURE_WRAP_S, wrap);
    gl.texParameteri(gl.TEXTURE_2D, gl.TEXTURE_WRAP_T, wrap);
    gl.texParameteri(gl.TEXTURE_2D, gl.TEXTURE_MIN_FILTER, gl.LINEAR);
    gl.texParameteri(gl.TEXTURE_2D, gl.TEXTURE_MAG_FILTER, gl.LINEAR);
    if (image) gl.texImage2D(gl.TEXTURE_2D, 0, gl.RGBA, gl.RGBA, gl.UNSIGNED_BYTE, image);
    return t;
  }

  gl.pixelStorei(gl.UNPACK_FLIP_Y_WEBGL, true);
  tex(0, src, gl.CLAMP_TO_EDGE);
  tex(1, mask, gl.CLAMP_TO_EDGE);
  const boltTex = tex(2, null, gl.CLAMP_TO_EDGE);

  const U = (n) => gl.getUniformLocation(prog, n);
  gl.uniform1i(U("u_src"), 0);
  gl.uniform1i(U("u_mask"), 1);
  gl.uniform1i(U("u_bolt"), 2);

  /* Normalise out of the reference space immediately. Nothing below this line
     cares how big the plate actually is. */
  const [RW, RH] = ref;
  const [cx0, cy0, cx1, cy1] = crop;
  const SW = RW, SH = RH;
  /* The mask and source are uploaded flipped, so the crop's v runs from the
     bottom. Getting this backwards puts the beard mask on his knees. */
  gl.uniform2f(U("u_crop0"), cx0 / SW, 1.0 - cy1 / SH);
  gl.uniform2f(U("u_crop1"), cx1 / SW, 1.0 - cy0 / SH);
  gl.uniform1f(U("u_loop"), loop);

  /** Source pixel -> crop UV, with v measured from the bottom to match. */
  const toCrop = (x, y) => [
    (x - cx0) / (cx1 - cx0),
    1.0 - (y - cy0) / (cy1 - cy0),
  ];
  gl.uniform2fv(U("u_hammer"), toCrop(528, 108));
  gl.uniform2fv(U("u_fist"), toCrop(424, 148));
  gl.uniform2fv(U("u_vent"), toCrop(300, 706));

  /* ── the arc canvas ────────────────────────────────────────────────────── */
  const BOLT = 512;
  const bc = document.createElement("canvas");
  bc.width = bc.height = BOLT;
  const bx = bc.getContext("2d");

  const [hx, hy] = [528, 108];
  const hUV = [(hx - cx0) / (cx1 - cx0), (hy - cy0) / (cy1 - cy0)]; // top-down, for 2D

  /* More than one charge per loop gives the loop two visibly different bolts
     and still repeats exactly; a short loop wants one, or the charge has no
     time to feel like charging. */
  const CYCLES = cycles;
  const CYCLE = loop / CYCLES;

  /** Charge, not flash. A long rise, a short peak, a fast fall, then rest. */
  function envelope(tc) {
    const RISE = 0.62, PEAK = 0.08, FALL = 0.14;   // fractions of a cycle
    const p = tc / CYCLE;
    if (p < RISE) {
      const k = p / RISE;
      return 0.10 + 0.42 * k * k * k;              // creeps, then builds
    }
    if (p < RISE + PEAK) return 1.0;
    if (p < RISE + PEAK + FALL) {
      const k = (p - RISE - PEAK) / FALL;
      return 1.0 - 0.94 * k * k;
    }
    return 0.06;
  }

  function drawBolts(t) {
    const idx = Math.floor(t / CYCLE) % CYCLES;
    const tc = t % CYCLE;
    const p = tc / CYCLE;
    bx.clearRect(0, 0, BOLT, BOLT);

    // Arcs only exist around the peak, and only briefly.
    const on = p > 0.50 && p < 0.80;
    if (!on) return;
    const k = (p - 0.50) / 0.30;
    const strength = Math.sin(k * Math.PI);

    const rng = mulberry32(1337 + idx * 977);
    const cxp = hUV[0] * BOLT, cyp = hUV[1] * BOLT;

    bx.lineCap = "round";
    bx.lineJoin = "round";
    bx.strokeStyle = "#fff";

    const arcs = 3 + Math.floor(rng() * 3);
    for (let i = 0; i < arcs; i++) {
      // Contained around the head: he is charging it, not throwing it.
      const a0 = rng() * Math.PI * 2;
      const a1 = a0 + (rng() - 0.5) * 2.6;
      const r0 = BOLT * (0.020 + rng() * 0.026);
      const r1 = BOLT * (0.052 + rng() * 0.055);
      const pts = bolt(
        rng,
        cxp + Math.cos(a0) * r0, cyp + Math.sin(a0) * r0,
        cxp + Math.cos(a1) * r1, cyp + Math.sin(a1) * r1,
        BOLT * 0.055, 5,
      );

      // A wide faint pass under a tight bright one: cheap bloom, no filter.
      for (const [w, alpha] of [[4.6, 0.13], [2.0, 0.40], [0.9, 1.0]]) {
        bx.globalAlpha = alpha * strength;
        bx.lineWidth = w;
        bx.beginPath();
        bx.moveTo(pts[0][0], pts[0][1]);
        for (let j = 1; j < pts.length; j++) bx.lineTo(pts[j][0], pts[j][1]);
        bx.stroke();
      }
    }
    bx.globalAlpha = 1;
  }

  const reduced = matchMedia("(prefers-reduced-motion: reduce)");

  /** Draw one frame at an absolute time in seconds. Pure: same t, same frame. */
  let debug = 0;
  function drawAt(t) {
    gl.uniform1f(U("u_debug"), debug);
    const tt = ((t % loop) + loop) % loop;
    drawBolts(tt);
    gl.activeTexture(gl.TEXTURE2);
    gl.bindTexture(gl.TEXTURE_2D, boltTex);
    gl.texImage2D(gl.TEXTURE_2D, 0, gl.RGBA, gl.RGBA, gl.UNSIGNED_BYTE, bc);

    gl.uniform1f(U("u_t"), tt);
    gl.uniform1f(U("u_charge"), envelope(tt % CYCLE));
    gl.uniform1f(U("u_amp"), reduced.matches ? 0.0 : 1.0);
    gl.viewport(0, 0, canvas.width, canvas.height);
    gl.drawArrays(gl.TRIANGLES, 0, 3);
  }

  let raf = 0;
  let t0 = performance.now();
  const frame = () => {
    raf = requestAnimationFrame(frame);
    drawAt((performance.now() - t0) / 1000);
  };

  return {
    drawAt,
    loop,
    set debugMasks(v) { debug = v ? 1 : 0; },
    start() { if (!raf) { t0 = performance.now(); raf = requestAnimationFrame(frame); } },
    stop() { cancelAnimationFrame(raf); raf = 0; },
  };
}
